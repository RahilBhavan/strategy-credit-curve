"""Pack only attributed SEC/official-statistics sources into <=16 KB Git blobs."""
import csv
import gzip
import hashlib
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
ALLOWED = {'www.sec.gov', 'data.sec.gov', 'home.treasury.gov', 'markets.newyorkfed.org', 'data-api.ecb.europa.eu'}


def freeze():
    frozen = ROOT / 'data/frozen'
    frozen.mkdir(exist_ok=True)
    rows = list(csv.DictReader((ROOT / 'data/raw/manifest.csv').open()))
    # Validate the complete ledger before producing any artifact.
    for row in rows:
        if urlparse(row['url']).hostname not in ALLOWED:
            raise ValueError('only SEC/official-statistics sources may be packed')
        path = (ROOT / 'data/raw' / row['path']).resolve()
        if not path.is_relative_to((ROOT / 'data/raw').resolve()):
            raise ValueError('source path escapes data/raw')
        if hashlib.sha256(path.read_bytes()).hexdigest() != row['sha256']:
            raise ValueError(f'source hash mismatch: {row["path"]}')
    index = []
    ignored = []
    for row in rows:
        path = ROOT / 'data/raw' / row['path']
        data = path.read_bytes()
        if len(data) <= 20000:
            continue
        packed = gzip.compress(data, mtime=0)
        stem = f'{len(index):03}'
        parts = []
        for n, offset in enumerate(range(0, len(packed), 16000)):
            name = f'{stem}-{n:03}.gzpart'
            (frozen / name).write_bytes(packed[offset:offset + 16000])
            parts.append(name)
        rel = path.relative_to(ROOT).as_posix()
        index.append({'path': rel, 'bytes': len(data), 'sha256': row['sha256'], 'parts': parts})
        ignored.append('/' + rel)
    (frozen / 'index.json').write_text(json.dumps(index, indent=1) + '\n')
    ignore = ROOT / '.gitignore'
    marker = '# Packed official sources (generated by scripts/freeze_sources.py)'
    base = ignore.read_text().split(marker)[0].rstrip()
    ignore.write_text(base + '\n\n' + marker + '\n' + '\n'.join(ignored) + '\n')
    print(f'Packed {len(index)} verified public source files')


if __name__ == '__main__':
    freeze()
