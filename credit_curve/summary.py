"""Plain-text and Markdown summaries of the two result files, built from the saved numbers only."""

CENTRAL = (0.6, 0.05)


def _money(value, currency='USD'):
    return f'{"€" if currency == "EUR" else "$"}{value:,.2f}'


LABELS = {'exchange_close': 'exchange daily closes; option volatility assumed',
          'synthetic_scenario': 'SYNTHETIC (authored, not market quotes)',
          'user_supplied': 'user-supplied (unverified)'}


def _label(kind):
    return LABELS[kind]


def preferred_rows(preferred):
    """One row per preferred: ticker, price, effective yield, benchmark, spread in bp."""
    out = []
    for row in preferred['rows']:
        if row['price'] is None:
            out.append((row['ticker'], 'no trade', 'excluded', row['benchmark'],
                        f'not computed (last trade {row["price_source"]["as_of"]})'))
            continue
        spread = f'{row["spread_bp"]:,.0f}'
        if row['ticker'] == 'STRC':
            spread += f' ({row["spread_vs_sofr_bp"]:,.0f} vs SOFR)'
        if row['ticker'] == 'STRK':
            low, high = row['straight_spread_range_bp']
            spread += f'; ex-option {row["straight_spread_bp"]:,.0f} ({low:,.0f} to {high:,.0f})'
        out.append((row['ticker'], _money(row['price'], row['currency']), f'{100 * row["effective_yield"]:.2f}%',
                    f'{row["benchmark"]} {100 * row["benchmark_effective"]:.2f}%', spread))
    return out


def note_rows(convertible):
    out = []
    for note in convertible['notes']:
        values = [s['value_per_1000_usd'] for s in note['scenarios']]
        central = next(s['value_per_1000_usd'] for s in note['scenarios']
                       if (s['vol_assumption'], s['spread_assumption']) == CENTRAL)
        supplied = note.get('supplied_assumption')
        own = 'none' if supplied is None else (f'{_money(supplied["value_per_1000_usd"])} '
                                            f'@ {100 * supplied["vol_assumption"]:g}% vol, '
                                            f'{1e4 * supplied["spread_assumption"]:,.0f} bp')
        out.append((note['terms']['name'], _money(note['terms']['conversion_price']),
                    _money(note['conversion_parity_per_1000_usd']), _money(central),
                    f'{_money(min(values))}–{_money(max(values))}', own))
    return out


def _table(header, rows):
    widths = [max(len(str(r[i])) for r in [header, *rows]) for i in range(len(header))]
    line = lambda r: '  '.join(str(c).ljust(w) for c, w in zip(r, widths)).rstrip()
    return [line(header), line(['-' * w for w in widths]), *map(line, rows)]


def render(preferred, convertible):
    """Terminal summary: what a capital-markets reader looks for first."""
    inputs = preferred['market_inputs']
    strk = next(r for r in preferred['rows'] if r['ticker'] == 'STRK')
    mstr = preferred['mstr']
    rates = inputs['rates']
    lines = [f'Strategy (MSTR) credit comparison, valuation date {inputs["valuation_date"]}',
             f'Prices and volatilities: {_label(inputs["kind"])}',
             f'Benchmark rates: {rates["kind"].replace("_", " ")} dated {rates["valuation_date"]}; '
             f'contract terms snapshot {inputs["contract_terms_snapshot"]}',
             f'MSTR spot {_money(mstr["price"])}. STRK converts into {strk["conversion_rate"]:g} MSTR share '
             f'(conversion price {_money(strk["conversion_price"])}; parity {_money(strk["conversion_parity"])} '
             f'per $100 stated).', '',
             'Preferreds (effective annual yield; spread over benchmark in bp)',
             *_table(('Ticker', 'Price', 'Yield', 'Benchmark', 'Spread (bp)'), preferred_rows(preferred)), '',
             'Convertible notes (USD per $1,000 face; model values, not quotes)',
             *_table(('Note', 'Conv. price', 'Parity', 'Central*', 'Grid low–high', 'Your vol/spread'),
                     note_rows(convertible)),
             '* Central: 60% volatility, 500 bp credit spread. Grid: 40/60/80% x 200/500/1,000 bp.']
    return '\n'.join(lines)


def markdown(preferred):
    """README table, regenerated by scripts/render_results.py and checked in CI."""
    inputs = preferred['market_inputs']
    strk = next(r for r in preferred['rows'] if r['ticker'] == 'STRK')
    price = {'exchange_close': f'Close {inputs["valuation_date"]}', 'synthetic_scenario': 'Price (synthetic)',
             'user_supplied': 'Price (user-supplied)'}[inputs['kind']]
    rows = ['| Preferred | ' + price + ' | Effective yield | Benchmark | Spread (bp) |',
            '|---|--:|--:|---|--:|']
    rows += ['| ' + ' | '.join(r) + ' |' for r in preferred_rows(preferred)]
    rates = inputs['rates']['kind'].replace('_', ' ')
    prices = {'exchange_close': f'are Nasdaq daily closes (`data/market/{inputs["valuation_date"]}/closes.json`)',
              'synthetic_scenario': 'are synthetic, authored inputs, not market quotes',
              'user_supplied': 'are user-supplied'}[inputs['kind']]
    excluded = ''.join(f' {r["ticker"]} is excluded. {r["excluded"]}' for r in preferred['rows'] if r['price'] is None)
    note = (f'Valuation date {inputs["valuation_date"]}; benchmark rates: {rates}. Prices and the MSTR spot '
            f'({_money(preferred["mstr"]["price"])}) {prices}.{excluded} '
            f'STRK conversion price {_money(strk["conversion_price"])}, parity {_money(strk["conversion_parity"])} '
            'per $100 stated. "Ex-option" removes an assumed 10-year call value (range: 5 to 20 years, two '
            'assumed volatilities).')
    return '\n'.join(rows) + '\n\n' + note
